/** The repo root: the folder with `pnpm-workspace.yaml`, above wherever Vitest runs. */
function repoRoot(): string {
  let dir = process.cwd();
  while (!existsSync(join(dir, 'pnpm-workspace.yaml'))) {
    const up = dirname(dir);
    if (up === dir) throw new Error('repo root not found');
    dir = up;
  }
  return dir;
}

const DIR = join(repoRoot(), 'shared/motion/vectors') + '/';
const WRITE = process.env.MOTION_VECTORS === 'write';
const COMMENT =
  'Generated by apps/web/src/board3d/motionVectors.test.ts from the web board, the reference. ' +
  "Don't edit: regenerate with `just motion-vectors` (docs/architecture/board-motion.md).";

/** The board's clock: 60 frames a second, sampled every third frame. */
const TICK = 1 / 60;
const EVERY = 3;
/** Five decimals: positions to a hundred-thousandth of a board unit. */
const r = (x: number) => Math.round(x * 1e5) / 1e5 || 0;

type Highlight = { pit?: number; kind: FrameKind } | null;

interface Move {
  before: GameState;
  pit: number;
  events: MoveEvent[];
  after: GameState;
  /** When its first frame shows (seconds). */
  at: number;
  by: 'human' | 'ai';
}

interface Input {
  t: number;
  /** The move and frame this input shows, for frames of a move. */
  move?: number;
  frame?: number;
  pits: number[];
  stores: [number, number];
  highlight: Highlight;
  total: number;
  legal: number[];
  hintPit: number | null;
  finished: boolean;
}

interface Vector {
  comment: string;
  name: string;
  description: string;
  variant: VariantRef;
  aspect: number;
  /** The game's pace for frame delays, and the 3D board's (0 = reduced motion: seeds snap). */
  frameSpeed: number;
  boardSpeed: number;
  tick: number;
  every: number;
  until: number;
  moves: Move[];
  inputs: Input[];
  samples: Sample[];
  final: { placement: number[][]; positions: number[][] };
}

interface Sample {
  t: number;
  /** x, y, z, grip, shown (0/1), side (+1 South, -1 North). */
  hand: number[];
  /** The camera's position (it always looks at the same point). */
  camera: number[];
  /** Seeds not at rest: id, x, y, z, tumble. */
  seeds: number[][];
  /** Rings glowing above 0.001: pit, opacity, r, g, b (linear). */
  rings: number[][];
}

// --- Building a scenario -----------------------------------------------------------------------

const core = loadCoreSync();
const sum = (xs: readonly number[]) => xs.reduce((a, b) => a + b, 0);

class Scenario {
  t = 0.25;
  moves: Move[] = [];
  inputs: Input[] = [];
  private restTotal = 0;
  private finished = false;

  constructor(
    readonly variant: VariantRef,
    readonly frameSpeed: number,
  ) {}

  /** What the board shows: its seed total, as the 3D scene keeps it (Board3D's `Scene`). */
  private push(input: Omit<Input, 'total' | 'finished'>): void {
    const onBoard = sum(input.pits) + input.stores[0] + input.stores[1];
    const moving = !!input.highlight;
    if (!moving && this.restTotal !== onBoard) this.restTotal = onBoard;
    const total = moving ? Math.max(this.restTotal, onBoard) : onBoard;
    this.inputs.push({ ...input, t: r(input.t), total, finished: this.finished });
  }

  /** The position at rest, with the player's legal pits lit (and maybe a hint). */
  idle(state: GameState, opts: { legal?: boolean; hint?: number; gap?: number } = {}): this {
    this.push({
      t: this.t,
      pits: [...state.pits],
      stores: [state.stores[0], state.stores[1]],
      highlight: null,
      legal: opts.legal ? core.legalMoves(this.variant, state) : [],
      hintPit: opts.hint ?? null,
    });
    this.t += opts.gap ?? 0.6;
    return this;
  }

  /** A move's frames at the game's pace; the computer first pauses, as the game does. */
  play(before: GameState, pit: number, by: 'human' | 'ai'): GameState {
    if (by === 'ai') this.t += (AI_PAUSE_MS * this.frameSpeed) / 1000;
    const result = core.applyMove(this.variant, before, pit);
    const move = this.moves.length;
    this.moves.push({ before, pit, events: result.events, after: result.state, at: r(this.t), by });
    buildFrames(before, pit, result.events, result.state).forEach((f, frame) => {
      this.push({
        t: this.t,
        move,
        frame,
        pits: f.pits,
        stores: f.stores,
        highlight: f.kind !== 'end' ? { pit: f.pit, kind: f.kind } : null,
        legal: [],
        hintPit: null,
      });
      this.t += frameDelay(f.kind, this.frameSpeed) / 1000;
    });
    return result.state;
  }

  finish(): this {
    this.finished = true;
    const last = this.inputs.at(-1)!;
    this.push({
      t: this.t + 0.1,
      pits: last.pits,
      stores: last.stores,
      highlight: null,
      legal: [],
      hintPit: null,
    });
    return this;
  }
}

/** A position from a game between two computers, just before a move that `wanted` picks. */
function findMove(
  variant: VariantRef,
  seed: number,
  wanted: (events: MoveEvent[], state: GameState) => boolean,
): { state: GameState; pit: number } {
  let state = core.newGame(variant, 'south');
  for (let ply = 0; ply < 600 && state.status === 'playing'; ply++) {
    const pit = core.aiMove(variant, state, 'easy', seed * 1000 + ply)!;
    const result = core.applyMove(variant, state, pit);
    if (wanted(result.events, state)) return { state, pit };
    state = result.state;
  }
  throw new Error('no game reached the wanted move');
}

const isType = (type: MoveEvent['type']) => (e: MoveEvent) => e.type === type;
const WIDE = 16 / 7.4;
const PHONE_WEB = 16 / 8.6;
const PHONE_TALL = 0.62;

function scenarios(): {
  name: string;
  description: string;
  aspect: number;
  boardSpeed: number;
  s: Scenario;
}[] {
  const standard = variantRef(core, 'cv.standard');
  const continuous = variantRef(core, 'cv.continuous');
  const out: ReturnType<typeof scenarios> = [];

  {
    const s = new Scenario(standard, PACE_3D);
    const opening = core.newGame(standard, 'south');
    s.idle(opening, { legal: true, hint: 2 });
    const afterYou = s.play(opening, 2, 'human');
    const ai = core.aiMove(standard, afterYou, 'medium', 7)!;
    const afterAi = s.play(afterYou, ai, 'ai');
    s.idle(afterAi, { legal: true });
    out.push({
      name: 'opening',
      description:
        "You sow your pit 3 from the opening, then the computer's hand answers from the far side.",
      aspect: WIDE,
      boardSpeed: PACE_3D,
      s,
    });
  }
  {
    const s = new Scenario(standard, PACE_3D);
    const { state, pit } = findMove(
      standard,
      3,
      (events, st) => st.to_move === 'south' && events.filter(isType('capture')).length >= 2,
    );
    s.idle(state, { legal: true });
    s.idle(s.play(state, pit, 'human'));
    out.push({
      name: 'captures-phone',
      description:
        'A move that captures from two pits, on a tall phone screen (the camera looks down more steeply).',
      aspect: PHONE_TALL,
      boardSpeed: PACE_3D,
      s,
    });
  }
  {
    const s = new Scenario(standard, PACE_3D);
    const lap: GameState = {
      pits: [13, 3, 3, 3, 3, 3, 3, 3, 3, 3, 3, 3],
      stores: [1, 1],
      to_move: 'south',
      moves_since_capture: 0,
      status: 'playing',
    };
    s.idle(lap, { legal: true });
    s.idle(s.play(lap, 0, 'human'));
    out.push({
      name: 'lap',
      description: 'Thirteen seeds go all the way round, skipping the pit they came from.',
      aspect: PHONE_WEB,
      boardSpeed: PACE_3D,
      s,
    });
  }
  {
    const s = new Scenario(continuous, PACE_3D);
    const { state, pit } = findMove(continuous, 5, (events) => events.some(isType('relay')));
    s.idle(state, { legal: state.to_move === 'south' });
    s.idle(s.play(state, pit, state.to_move === 'south' ? 'human' : 'ai'));
    out.push({
      name: 'relay',
      description: 'Continuous sowing: the hand picks up the pit it ended in and sows on.',
      aspect: WIDE,
      boardSpeed: PACE_3D,
      s,
    });
  }
  {
    const s = new Scenario(standard, PACE_3D);
    const { state, pit } = findMove(standard, 11, (events) => events.some(isType('game_over')));
    s.idle(state, { legal: state.to_move === 'south' });
    s.play(state, pit, state.to_move === 'south' ? 'human' : 'ai');
    s.finish();
    out.push({
      name: 'game-end',
      description: "The game's last move, then the camera eases into its end-of-game angle.",
      aspect: WIDE,
      boardSpeed: PACE_3D,
      s,
    });
  }
  {
    const speed = REDUCED_MOTION_SPEED * PACE_3D;
    const s = new Scenario(standard, speed);
    const opening = core.newGame(standard, 'south');
    s.idle(opening, { legal: true });
    s.idle(s.play(opening, 2, 'human'));
    out.push({
      name: 'reduced-motion',
      description:
        'With reduced motion, frames come faster and seeds snap into place: no hand, no camera moves.',
      aspect: WIDE,
      boardSpeed: 0,
      s,
    });
  }
  {
    const s = new Scenario(standard, PACE_3D);
    const opening = core.newGame(standard, 'south');
    s.idle(opening, { legal: true });
    s.idle(s.play(opening, 2, 'human'), { gap: 0.8 });
    s.idle(opening, { legal: true });
    out.push({
      name: 'undo',
      description: 'Undo: the seeds fly back to where they were.',
      aspect: WIDE,
      boardSpeed: PACE_3D,
      s,
    });
  }
  return out;
}

// --- Playing a vector --------------------------------------------------------------------------

function simulate(v: Pick<Vector, 'inputs' | 'aspect' | 'boardSpeed' | 'until' | 'variant'>) {
  const layout = layoutFor(v.inputs[0]!.pits.length);
  const choreo = createChoreography();
  const rig = createCameraRig();
  const rings = createRings(layout.n * 2);
  const camera = new Vector3();
  const samples: Sample[] = [];
  let current: Input | null = null;
  let next = 0;
  for (let tick = 0; tick * TICK <= v.until + 1e-9; tick++) {
    const now = tick * TICK;
    while (next < v.inputs.length && v.inputs[next]!.t <= now + 1e-9) {
      current = v.inputs[next++]!;
      applyFrame(
        choreo,
        layout,
        current.total,
        {
          pits: current.pits,
          stores: current.stores,
          highlight: current.highlight,
          speed: v.boardSpeed,
        },
        current.t,
      );
      setCameraInputs(
        rig,
        {
          finished: current.finished,
          highlightKind: current.highlight?.kind,
          speed: v.boardSpeed,
        },
        current.t,
      );
    }
    const dt = tick === 0 ? 0 : TICK;
    stepChoreography(choreo, now, dt);
    stepCameraRig(rig, now, dt, v.aspect, camera);
    if (current) {
      const targets = ringTargets(layout.n, {
        legal: current.legal,
        highlight: current.highlight,
        hintPit: current.hintPit,
      });
      stepRings(rings, targets, dt, v.boardSpeed);
    }
    if (tick % EVERY === 0) {
      const h = choreo.hand;
      samples.push({
        t: r(now),
        hand: [r(h.pos.x), r(h.pos.y), r(h.pos.z), r(h.grip), now < h.hideAt ? 1 : 0, h.side],
        camera: [r(camera.x), r(camera.y), r(camera.z)],
        seeds: choreo.motions.flatMap((m, id) =>
          m.mode === 'rest' ? [] : [[id, r(m.pos.x), r(m.pos.y), r(m.pos.z), r(m.tumble)]],
        ),
        rings: rings.flatMap((ring, i) =>
          ring.opacity > 1e-3
            ? [[i, r(ring.opacity), r(ring.color.r), r(ring.color.g), r(ring.color.b)]]
            : [],
        ),
      });
    }
  }
  return {
    samples,
    final: {
      placement: (choreo.placement ?? []).map((p) => [p.container, p.slot]),
      positions: choreo.motions.map((m) => [r(m.pos.x), r(m.pos.y), r(m.pos.z)]),
    },
  };
}

function build(): Vector[] {
  return scenarios().map(({ name, description, aspect: exact, boardSpeed, s }) => {
    // Simulate with the values as written, so a replay of the file gives the same samples.
    const aspect = r(exact);
    const until = r(s.inputs.at(-1)!.t + 2.5);
    const base = { inputs: s.inputs, aspect, boardSpeed, until, variant: s.variant };
    return {
      comment: COMMENT,
      name,
      description,
      variant: s.variant,
      aspect,
      frameSpeed: r(s.frameSpeed),
      boardSpeed: r(boardSpeed),
      tick: TICK,
      every: EVERY,
      until,
      moves: s.moves,
      inputs: s.inputs,
      ...simulate(base),
    };
  });
}

function timings() {
  return {
    comment: COMMENT,
    frameBaseMs: FRAME_BASE_MS,
    pace3d: PACE_3D,
    reducedMotionSpeed: REDUCED_MOTION_SPEED,
    aiPauseMs: AI_PAUSE_MS,
    frameTones: FRAME_TONES,
    endTones: END_TONES,
  };
}

function seedLooks() {
  const total = 48;
  const colors = seedColors(total);
  return {
    comment: COMMENT,
    total,
    orientations: seedOrientations(total).map((q) => [r(q.x), r(q.y), r(q.z), r(q.w)]),
    colors: Array.from({ length: total }, (_, i) => [
      r(colors[i * 3]!),
      r(colors[i * 3 + 1]!),
      r(colors[i * 3 + 2]!),
    ]),
  };
}

/** One sample or input per line, so a diff shows what moved. */
function stringify(value: object): string {
  const lines = Object.entries(value).map(([k, v]) => {
    if (Array.isArray(v) && v.length > 0 && typeof v[0] === 'object') {
      return `  ${JSON.stringify(k)}: [\n${v.map((x) => `    ${JSON.stringify(x)}`).join(',\n')}\n  ]`;
    }
    return `  ${JSON.stringify(k)}: ${JSON.stringify(v)}`;
  });
  return `{\n${lines.join(',\n')}\n}\n`;
}

const read = (file: string) =>
  JSON.parse(readFileSync(DIR + file, 'utf8')) as Record<string, unknown>;

/** Deep equality, with numbers equal to within `tol`. */
function near(a: unknown, b: unknown, tol: number, path = ''): string | null {
  if (typeof a === 'number' && typeof b === 'number') {
    return Math.abs(a - b) <= tol ? null : `${path}: ${a} != ${b}`;
  }
  if (Array.isArray(a) && Array.isArray(b)) {
    if (a.length !== b.length) return `${path}: length ${a.length} != ${b.length}`;
    for (let i = 0; i < a.length; i++) {
      const d = near(a[i], b[i], tol, `${path}[${i}]`);
      if (d) return d;
    }
    return null;
  }
  if (a && b && typeof a === 'object' && typeof b === 'object') {
    const keys = new Set([...Object.keys(a), ...Object.keys(b)]);
    for (const k of keys) {
      const d = near(
        (a as Record<string, unknown>)[k],
        (b as Record<string, unknown>)[k],
        tol,
        `${path}.${k}`,
      );
      if (d) return d;
    }
    return null;
  }
  return a === b ? null : `${path}: ${JSON.stringify(a)} != ${JSON.stringify(b)}`;
}

describe('motion vectors (shared/motion/vectors)', () => {
  if (WRITE) {
    it('writes the vectors from the web board', () => {
      mkdirSync(DIR, { recursive: true });
      for (const v of build()) writeFileSync(`${DIR}${v.name}.json`, stringify(v));
      writeFileSync(`${DIR}timings.json`, stringify(timings()));
      writeFileSync(`${DIR}seed-looks.json`, stringify(seedLooks()));
    });
    return;
  }

  it('records the timings and tones the web plays', () => {
    expect(near(timings(), read('timings.json'), 0)).toBeNull();
  });

  it('records how each seed looks', () => {
    expect(near(seedLooks(), read('seed-looks.json'), 2e-5)).toBeNull();
  });

  const files = readdirSync(DIR).filter(
    (f) => f.endsWith('.json') && f !== 'timings.json' && f !== 'seed-looks.json',
  );

  it('has the scenarios', () => {
    expect(files.length).toBeGreaterThanOrEqual(7);
  });

  for (const file of files) {
    describe(file, () => {
      const v = read(file) as unknown as Vector;

      it("turns each move into the recorded frames, at the game's pace", () => {
        let end = 0;
        v.moves.forEach((m, i) => {
          if (m.by === 'ai' && i > 0) {
            expect(m.at - end).toBeCloseTo((AI_PAUSE_MS * v.frameSpeed) / 1000, 4);
          }
          const frames = buildFrames(m.before, m.pit, m.events, m.after);
          const shown = v.inputs.filter((x) => x.move === i);
          expect(shown.map((x) => x.frame)).toEqual(frames.map((_, j) => j));
          let t = m.at;
          frames.forEach((f, j) => {
            const x = shown[j]!;
            expect(x.t).toBeCloseTo(t, 4);
            expect(x.pits).toEqual(f.pits);
            expect(x.stores).toEqual(f.stores);
            expect(x.highlight).toEqual(f.kind !== 'end' ? { pit: f.pit, kind: f.kind } : null);
            t += frameDelay(f.kind, v.frameSpeed) / 1000;
          });
          end = t;
        });
      });

      it('plays the recorded hand, seeds, camera and rings', () => {
        const got = simulate(v);
        expect(near(got.samples, v.samples, 2e-5, 'samples')).toBeNull();
        expect(near(got.final, v.final, 2e-5, 'final')).toBeNull();
      });
    });
  }
});
