/**
 * Motion vectors (docs/architecture/board-motion.md): the web's 3D board is the reference for
 * how a move looks, and every platform must play the same frames, hand, seeds, camera and rings.
 *
 * Each vector in `shared/motion/vectors/` holds real moves from the engine, the board's inputs
 * over time (display frames at the game's pace), and what the board did on a 60 Hz clock: the
 * hand, every moving seed, the camera and the lit rings, plus where every seed ends. This test
 * replays them against the web's code (`choreography.ts`, `cameraRig.ts`, `rings.ts`), and the
 * Android app's `MotionVectorsTest` replays them against its own.
 *
 * Regenerate after an intended change with `just motion-vectors` (this test with
 * `MOTION_VECTORS=write`), then make every platform pass them again.
 */
